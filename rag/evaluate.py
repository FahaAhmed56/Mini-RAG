"""Evaluate all retrievers on 40 questions, tune the LSA dimension, save charts, export the index for the web app.

    python rag/evaluate.py
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from engine import Index
from text import tokenize

ROOT = Path(__file__).resolve().parent.parent
METHODS = ["keyword", "tfidf", "bm25", "lsa", "hybrid"]
NAMES = {"keyword": "Keyword match", "tfidf": "TF-IDF", "bm25": "BM25", "lsa": "LSA embeddings", "hybrid": "Hybrid (BM25+LSA)"}


def evaluate(index, questions, method):
    rows = []
    for q in questions:
        ranked = index.rank_docs(q["q"], method)
        r = ranked.index(q["doc"]) + 1
        rows.append({"type": q["type"], "rank": r})
    res = {}
    for t in ("lexical", "paraphrase", "all"):
        rr = [x["rank"] for x in rows if t == "all" or x["type"] == t]
        res[t] = {"recall@1": np.mean([r == 1 for r in rr]), "recall@3": np.mean([r <= 3 for r in rr]),
                  "mrr": np.mean([1 / r for r in rr])}
    return res, [x["rank"] for x in rows]


def main():
    docs = json.load(open(ROOT / "data" / "knowledge_base.json"))
    questions = json.load(open(ROOT / "data" / "questions.json"))
    index = Index(docs)
    print(f"{len(docs)} documents -> {len(index.chunks)} chunks, vocabulary of {len(index.vocab)} word stems")

    # ---------- tune LSA dimensions ("training" the embedding size) ----------
    dims = [4, 8, 12, 16, 24, 32, 48, 64, len(index.chunks) - 1]
    sweep = []
    for k in dims:
        index.fit_lsa(k)
        r, _ = evaluate(index, questions, "lsa")
        sweep.append((k, r["all"]["mrr"], index.explained))
    best_k = max(sweep, key=lambda x: (round(x[1], 3), -x[0]))[0]          # best MRR, fewest dims on ties
    index.fit_lsa(best_k)
    print("LSA dimension sweep (k, MRR, variance kept):", [(k, round(m, 3), f"{e:.0%}") for k, m, e in sweep])
    print(f"Chosen LSA dimensions: {best_k}")

    results, ranks = {}, {}
    for m in METHODS:
        results[m], ranks[m] = evaluate(index, questions, m)
        a, p = results[m]["all"], results[m]["paraphrase"]
        print(f"{NAMES[m]:20s} recall@1 {a['recall@1']:.0%}  recall@3 {a['recall@3']:.0%}  MRR {a['mrr']:.3f}   "
              f"| paraphrase recall@1 {p['recall@1']:.0%}")

    misses = {m: [questions[i]["q"] for i, r in enumerate(ranks[m]) if r > 1] for m in METHODS}
    print("\nHybrid still misses (not ranked #1):", misses["hybrid"])

    # ---------- export everything the browser needs ----------
    export = {
        "chunks": index.chunks, "vocab": index.vocab, "idf": index.idf.round(6).tolist(),
        "bm25_idf": index.bm25_idf.round(6).tolist(), "lengths": index.lengths.tolist(), "avgdl": index.avgdl,
        "tf": [{str(j): int(c) for j, c in enumerate(row) if c} for row in index.tf],
        "V": index.V.round(6).tolist(), "chunk_emb": index.chunk_emb.round(6).tolist(), "k": best_k,
        "results": {m: {t: {k: round(float(v), 4) for k, v in d.items()} for t, d in results[m].items()} for m in METHODS},
        "examples": [q["q"] for q in questions if q["type"] == "paraphrase"][:6],
    }
    (ROOT / "web" / "index_data.js").write_text("// Auto-generated by rag/evaluate.py\nconst INDEX = " + json.dumps(export) + ";\n")
    fixtures = [{"q": q["q"], "tokens": tokenize(q["q"]),
                 "top": {m: [i for i, _ in index.search(q["q"], m, 3)] for m in METHODS},
                 "answer": index.answer(q["q"])["sentence"]} for q in questions]
    json.dump(fixtures, open(ROOT / "web" / "test_fixtures.json", "w"))
    json.dump({"results": export["results"], "lsa_sweep": sweep, "misses": misses}, open(ROOT / "rag" / "results.json", "w"), indent=1, default=float)

    # ---------- charts ----------
    plt.style.use("seaborn-v0_8-whitegrid")
    x = np.arange(len(METHODS)); w = 0.38
    fig, ax = plt.subplots(figsize=(10, 4.4))
    for off, t, col in ((-w / 2, "lexical", "#2563eb"), (w / 2, "paraphrase", "#f97316")):
        vals = [results[m][t]["recall@1"] * 100 for m in METHODS]
        bars = ax.bar(x + off, vals, w, color=col, label=f"{t} questions (20)")
        ax.bar_label(bars, fmt="%.0f%%", fontsize=9)
    ax.set(xticks=x, xticklabels=[NAMES[m] for m in METHODS], ylabel="right document ranked #1 (%)", ylim=(0, 125),
           title="Retrieval accuracy: same words vs paraphrased questions")
    ax.legend(loc="upper center", ncol=2); fig.tight_layout(); fig.savefig(ROOT / "screenshots" / "retrieval_accuracy.png", dpi=130)

    fig, ax = plt.subplots(figsize=(10, 3.8))
    for i, (metric, col) in enumerate((("recall@1", "#94a3b8"), ("recall@3", "#22c55e"), ("mrr", "#7c3aed"))):
        vals = [results[m]["all"][metric] * (100 if metric != "mrr" else 100) for m in METHODS]
        bars = ax.bar(x + (i - 1) * 0.27, vals, 0.27, color=col, label=metric.upper() if metric == "mrr" else metric)
        ax.bar_label(bars, fmt="%.0f", fontsize=8)
    ax.set(xticks=x, xticklabels=[NAMES[m] for m in METHODS], ylabel="score (%; MRR × 100)", ylim=(0, 125),
           title="All 40 questions: recall@1, recall@3 and mean reciprocal rank")
    ax.legend(loc="upper center", ncol=3); fig.tight_layout(); fig.savefig(ROOT / "screenshots" / "all_metrics.png", dpi=130)

    fig, ax = plt.subplots(figsize=(9, 3.8))
    ax.plot([s[0] for s in sweep], [s[1] for s in sweep], "o-", color="#7c3aed", lw=2.5, label="LSA retrieval MRR")
    ax.plot([s[0] for s in sweep], [s[2] for s in sweep], "s--", color="#94a3b8", lw=1.5, label="share of information kept by SVD")
    ax.axvline(best_k, color="#7c3aed", ls=":", lw=1); ax.text(best_k + 1, 0.15, f"chosen k = {best_k}", color="#6d28d9")
    ax.set(title="Tuning embedding size: too few dimensions blur topics, too many add noise", xlabel="LSA dimensions (k)", ylim=(0, 1.05))
    ax.legend(loc="lower right"); fig.tight_layout(); fig.savefig(ROOT / "screenshots" / "lsa_dimensions.png", dpi=130)
    print("Saved charts to screenshots/, index to web/index_data.js")


if __name__ == "__main__":
    main()
